# key: (on white, on black). The sheet Paul approved on Nov 25.
COLORS = {
    "home": ("#111111", "#F2F2EC"), "sessions": ("#1A9381", "#26B39C"), "meetings": ("#93407F", "#D07AB9"),
    "dockets": ("#7A5CE6", "#9580F0"), "explainers": ("#D9466E", "#EE6F8C"), "newsletter": ("#E8A317", "#E8A317"),
    "wire": ("#7F9410", "#C5D63A"), "records": ("#4E5A66", "#A7B2BD"), "search": ("#3D3D3D", "#CFCFCF"),
    "calendar": ("#C25A14", "#F08A44"), "lastnight": ("#4A3B8C", "#8F80D6"), "regions": ("#2F8A3E", "#5CC46B"),
    "positions": ("#8C5A3C", "#C99470"), "legislature": ("#9C7A0C", "#D9B23A"), "about": ("#7A7466", "#B8B2A3"),
}


def _lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= .03928 else ((x + .055) / 1.055) ** 2.4 for x in c]
    return .2126 * c[0] + .7152 * c[1] + .0722 * c[2]


def _cr(a, b):
    x, y = sorted([_lum(a), _lum(b)], reverse=True)
    return (x + .05) / (y + .05)


def icon(k):
    # Strokes thicker, so the shapes hold at menu size.
    s = re.sub(r'stroke-width="([\d.]+)"', lambda m: f'stroke-width="{float(m.group(1))*1.9:g}"', S[k])
    s = re.sub(r"(\d+\.\d)\d+", r"\1", s)
    svg = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 2 64 60'>{s}</svg>".replace('"', "'")
    enc = svg.replace("%", "%25").replace("<", "%3C").replace(">", "%3E").replace("#", "%23")
    return f'url("data:image/svg+xml,{enc}")'


def block():
    out = [START]
    for k, (light, dark) in COLORS.items():
        text = "#FFFFFF" if _cr(light, "#FFFFFF") >= _cr(light, "#111111") else "#111111"
        out.append(f".k-{k}{{--sc:{light};--sd:{dark};--st:{text};--si:{icon(k)}}}")
    out.append(END)
    return "\n".join(out)


def main():
    css = CSS.read_text()
    if START in css:
        css = css[:css.index(START)] + block() + css[css.index(END) + len(END):]
    else:
        css = css.rstrip("\n") + "\n" + block() + "\n"
    CSS.write_text(css)


if __name__ == "__main__":
    main()
